package Operators;


public class Arithmetic {
    public static void main(String[] args) {

    int a = 6;
    int b = 30;

    int multiple = a * b;
    int addition = a + b;
    int substraction = b - a;
    int division = b / a;
                                                                    //Output
    System.out.println("Addition: " + addition);                    //Addition: 36
    System.out.println("Substraction: " + substraction);            //Substraction: 24
    System.out.println("Muliplication: " + multiple);               //Multiplication: 180
    System.out.println("Division: " + division);                    //Division: 5
    }
}



